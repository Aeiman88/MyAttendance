// Copies the pure TypeScript modules shared with the server (time, attendance rules, geofence)
// and the Leaflet map library into the app. Run after changing them in ../src/lib.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const app = path.resolve(here, "..");
const server = path.resolve(app, "..");

for (const name of ["time.ts", "rules.ts", "geo.ts"]) {
  const src = fs.readFileSync(path.join(server, "src/lib", name), "utf8");
  const banner = `// Copied from ../src/lib/${name} by scripts/sync-shared.mjs. Edit the original, then run npm run sync-shared.\n`;
  fs.writeFileSync(path.join(app, "src/shared", name), banner + src);
  console.log("copied", name);
}

const leaflet = path.join(app, "node_modules/leaflet/dist");
const pick = fs.existsSync(leaflet) ? leaflet : path.join(server, "node_modules/leaflet/dist");
const js = fs.readFileSync(path.join(pick, "leaflet.js"), "utf8");
const css = fs.readFileSync(path.join(pick, "leaflet.css"), "utf8");
fs.writeFileSync(
  path.join(app, "src/map/leaflet-assets.ts"),
  `// Leaflet 1.9.4 (BSD-2-Clause), inlined so the map works without a CDN. Generated by scripts/sync-shared.mjs.\n` +
    `export const LEAFLET_JS = ${JSON.stringify(js)};\nexport const LEAFLET_CSS = ${JSON.stringify(css)};\n`,
);
console.log("wrote leaflet assets", Math.round((js.length + css.length) / 1024), "KB");
